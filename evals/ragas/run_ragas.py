#!/usr/bin/env python3
"""Run Ragas metrics over exported RAG evaluation rows.

Input JSONL rows are generated by:

    bun run eval:export evals/questions.json evals/ragas-dataset.jsonl 3

Each row must contain:
- user_input
- response
- retrieved_contexts
- reference

This script intentionally keeps Ragas isolated in Python while the production RAG
pipeline stays TypeScript/Bun.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any

from datasets import Dataset
from langchain_openai import ChatOpenAI, OpenAIEmbeddings
from ragas import evaluate


def load_rows(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line_number, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            required = ["user_input", "response", "retrieved_contexts", "reference"]
            missing = [key for key in required if key not in row]
            if missing:
                raise ValueError(f"Row {line_number} missing required keys: {missing}")
            rows.append(row)
    if not rows:
        raise ValueError(f"No rows found in {path}")
    return rows


def build_dataset(rows: list[dict[str, Any]]) -> Dataset:
    # Ragas 0.2+ uses user_input/response/retrieved_contexts/reference.
    return Dataset.from_list(
        [
            {
                "user_input": row["user_input"],
                "response": row["response"],
                "retrieved_contexts": row["retrieved_contexts"],
                "reference": row["reference"],
            }
            for row in rows
        ]
    )


def load_metrics() -> list[Any]:
    # Prefer modern Ragas metric classes. Fall back to legacy names if needed.
    try:
        from ragas.metrics.collections import Faithfulness, LLMContextPrecisionWithoutReference, LLMContextRecall, ResponseRelevancy

        return [
            Faithfulness(),
            ResponseRelevancy(),
            LLMContextPrecisionWithoutReference(),
            LLMContextRecall(),
        ]
    except Exception:
        from ragas.metrics import answer_relevancy, context_precision, context_recall, faithfulness

        return [faithfulness, answer_relevancy, context_precision, context_recall]


def main() -> None:
    parser = argparse.ArgumentParser(description="Run Ragas metrics over an exported RAG eval JSONL dataset.")
    parser.add_argument("dataset", nargs="?", default="../ragas-dataset.jsonl", help="Path to exported JSONL dataset")
    parser.add_argument("--out", default="../ragas-report.json", help="Where to write the Ragas JSON report")
    args = parser.parse_args()

    dataset_path = Path(args.dataset).resolve()
    output_path = Path(args.out).resolve()

    if not os.getenv("OPENAI_API_KEY"):
        raise SystemExit("OPENAI_API_KEY is required for Ragas judge/embedding calls")

    rows = load_rows(dataset_path)
    dataset = build_dataset(rows)
    metrics = load_metrics()

    judge_model = os.getenv("RAGAS_LLM_MODEL") or "gpt-4o-mini"
    embedding_model = os.getenv("RAGAS_EMBEDDING_MODEL") or os.getenv("EMBEDDING_MODEL") or "text-embedding-3-small"

    llm = ChatOpenAI(model=judge_model)
    embeddings = OpenAIEmbeddings(model=embedding_model)

    result = evaluate(dataset=dataset, metrics=metrics, llm=llm, embeddings=embeddings)
    report = result.to_pandas().to_dict(orient="records")

    output_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(
        json.dumps(
            {
                "dataset": str(dataset_path),
                "out": str(output_path),
                "rows": len(rows),
                "judgeModel": judge_model,
                "embeddingModel": embedding_model,
                "metrics": [getattr(metric, "name", metric.__class__.__name__) for metric in metrics],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
